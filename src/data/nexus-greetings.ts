export function getRandomGreeting(category?: string): NexusGreeting {
  const pool = category && category !== 'all'
    ? NEXUS_GREETINGS.filter(g => g.cat === category)
    : NEXUS_GREETINGS;
  return pool[Math.floor(Math.random() * pool.length)];
}

export function getCategoryCounts(): Record<string, number> {
  const counts: Record<string, number> = { all: NEXUS_GREETINGS.length };
  for (const g of NEXUS_GREETINGS) {
    counts[g.cat] = (counts[g.cat] || 0) + 1;
  }
  return counts;
}
