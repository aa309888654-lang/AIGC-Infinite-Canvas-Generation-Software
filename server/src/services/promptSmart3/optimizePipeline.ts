const concurrencyLimiter = new Semaphore(5);

let initialized = false;

export async function initOptimizePipeline(
  providers: ProviderConfig[],
  resolveApiKey: (providerName: string, envKey?: string) => Promise<string | undefined>
): Promise<void> {
  if (initialized) return;
  await initProviders(providers, resolveApiKey);
  initialized = true;
  console.log(`[PromptSmart3] Initialized with ${getProviderCount()} providers`);
}

export interface OptimizePromptResult {
  optimizedPrompt: string;
  provider: string;
  cached: boolean;
  latencyMs: number;
  qualityReport?: PromptQualityReport;
  modelProfile?: string;
}

export async function optimizePrompt(
  prompt: string,
  scenario?: string,
  category?: string,
  models?: string[],
  preferredProvider?: string,
  prePrompt?: string,
  fixedProvider?: ProviderConfig,
  cacheScope?: string
): Promise<OptimizePromptResult> {
  const culturalRule = getCulturalDefaultRule(prompt);
  let fullPrompt = `【用户原始提示词】\n${prompt}`;
  if (prePrompt) {
    fullPrompt = `【用户自定义指令】\n${prePrompt}\n\n` + fullPrompt;
  }
  if (models && models.length > 0) {
    const imageModels = [
      'image-01',
      'Seedream-5.0-lite',
      'Doubao-Seedream-4.5',
      'doubao-seedream-5-0-pro',
      'gpt-image-1',
    ];
    const videoModels = ['Doubao-Seedance-2.0', 'Doubao-Seedance-2.0-fast', 'Seedance-1.5-pro'];
    const matchedImageModels =
      scenario === 'image' ? models : models.filter((m: string) => imageModels.includes(m));
    const matchedVideoModels =
      scenario === 'video' ? models : models.filter((m: string) => videoModels.includes(m));
    const otherModels = models.filter(
      (m: string) =>
        !matchedImageModels.includes(m) &&
        !matchedVideoModels.includes(m) &&
        !imageModels.includes(m) &&
        !videoModels.includes(m)
    );

    const parts: string[] = [];
    if (matchedImageModels.length > 0)
      parts.push(`【目标图片模型】${matchedImageModels.join('、')}`);
    if (matchedVideoModels.length > 0)
      parts.push(`【目标视频模型】${matchedVideoModels.join('、')}`);
    if (otherModels.length > 0) parts.push(`【模板偏好】${otherModels.join('，')}`);
    fullPrompt = [
      prePrompt ? `【用户自定义指令】\n${prePrompt}` : '',
      `【用户原始提示词】\n${prompt}`,
      ...parts,
    ]
      .filter(Boolean)
      .join('\n\n');
  }

  const modelProfile = resolvePromptModelProfile(scenario, models);
  const cached = fixedProvider
    ? null
    : await getCachedResult(fullPrompt, scenario, category, cacheScope);
  if (cached) {
    return {
      optimizedPrompt: cached,
      provider: 'cache',
      cached: true,
      latencyMs: 0,
      modelProfile: modelProfile.label,
    };
  }

  await concurrencyLimiter.acquire();
  const startTime = Date.now();

  try {
    const domainPrompts = buildSystemPromptV2(scenario, category, culturalRule, models);
    const professionalPrompt = buildProfessionalOptimizationPrompt({
      scenario,
      category,
      models,
      expansionRules: domainPrompts.expansion,
      qualityRules: domainPrompts.quality,
    });

    // 单次模型调用内完成意图合同、模型适配、生成和自检，降低优化等待时间。
    const optimizationResult = await routeRequest(
      [],
      [
        { role: 'system', content: professionalPrompt.systemPrompt },
        { role: 'user', content: fullPrompt },
      ],
      (tried) => {
        if (fixedProvider) {
          if (tried.has(fixedProvider.name)) return null;
          return { config: fixedProvider, name: fixedProvider.name };
        }
        if (preferredProvider && !tried.has(preferredProvider)) {
          const preferred = selectProviderByName(preferredProvider);
          if (preferred && !preferred.circuitBreaker.isOpen) {
            return { config: preferred.config, name: preferred.config.name };
          }
        }
        const entry = selectProvider(tried);
        if (!entry) return null;
        return { config: entry.config, name: entry.config.name };
      },
      reportSuccess,
      reportFailure
    );

    const parsed = parseProfessionalOptimizationResponse(
      optimizationResult.content || '',
      professionalPrompt.modelProfile
    );
    const sanitizedContent = sanitizeOptimizedPrompt(parsed.optimizedPrompt, scenario);
    if (!sanitizedContent) {
      throw new Error('优化模型未返回有效提示词');
    }

    await recordProviderCall(optimizationResult.provider, true, Date.now() - startTime);
    if (!fixedProvider) {
      await setCachedResult(fullPrompt, sanitizedContent, scenario, category, undefined, cacheScope);
    }

    return {
      optimizedPrompt: sanitizedContent,
      provider: optimizationResult.provider,
      cached: false,
      latencyMs: Date.now() - startTime,
      qualityReport: parsed.qualityReport,
      modelProfile: parsed.modelProfile,
    };
  } finally {
    concurrencyLimiter.release();
  }
}

